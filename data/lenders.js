export const seedLendersIfEmpty = async (Lender) => {
  const count = await Lender.countDocuments();
  if (count > 0) return { seeded: false, count };
  await Lender.insertMany(lenderSeedData.map((lender) => ({ ...lender, active: true })));
  return { seeded: true, count: lenderSeedData.length };
};

export const syncLenders = seedLendersIfEmpty;
